"""Content-addressed cache for model calls.

Every model call is keyed by ``sha256(model_id + prompt + params)`` and stored
with its response, token counts, latency and cost. Two things follow from that.

A rerun with an unchanged cache reproduces results exactly and costs nothing,
which is what makes a published number checkable by anyone who clones the repo.

And a changed prompt template changes its hash, which changes every key derived
from it. Entries under the old hash are not reused, they are simply never asked
for again. That is deliberate: silently serving a response generated by a
different prompt would make a run's manifest describe something the run did not
do.

The cache never invents a response. A miss is a miss and the caller has to make
a real call, which is what ``hits`` and ``misses`` exist to prove afterwards.
"""

from __future__ import annotations

import hashlib
import json
import sqlite3
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Any

__all__ = ["CacheStats", "LLMCache", "ModelCall", "call_key"]


@dataclass(frozen=True)
class ModelCall:
    """One model call, request and response together.

    ``cost_usd`` is recorded even when it is zero, which is the honest value for
    a local model. Leaving it null would make a cost-per-correct-answer figure
    quietly undefined for the local backend.
    """

    key: str
    model_id: str
    prompt: str
    params_json: str
    response: str
    prompt_tokens: int
    completion_tokens: int
    latency_ms: float
    cost_usd: float
    created_at: str

    @property
    def total_tokens(self) -> int:
        return self.prompt_tokens + self.completion_tokens

    def to_json(self) -> dict[str, Any]:
        return asdict(self)


@dataclass(frozen=True)
class CacheStats:
    hits: int
    misses: int
    stored: int

    @property
    def calls(self) -> int:
        return self.hits + self.misses


def call_key(model_id: str, prompt: str, params: dict[str, Any]) -> str:
    """The cache key. Params are serialized with sorted keys so that two calls

    differing only in dict ordering hash the same.
    """
    material = "\x00".join(
        [model_id, prompt, json.dumps(params, sort_keys=True, separators=(",", ":"))]
    )
    return hashlib.sha256(material.encode("utf-8")).hexdigest()


_SCHEMA = """
CREATE TABLE IF NOT EXISTS model_calls (
    key TEXT PRIMARY KEY NOT NULL,
    model_id TEXT NOT NULL,
    prompt TEXT NOT NULL,
    params_json TEXT NOT NULL,
    response TEXT NOT NULL,
    prompt_tokens INTEGER NOT NULL,
    completion_tokens INTEGER NOT NULL,
    latency_ms REAL NOT NULL,
    cost_usd REAL NOT NULL,
    created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_model_calls_model ON model_calls (model_id);
"""


class LLMCache:
    """SQLite-backed store of model calls, keyed by content."""

    def __init__(self, path: Path) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        self._connection = sqlite3.connect(path)
        self._connection.executescript(_SCHEMA)
        self._connection.commit()
        self._hits = 0
        self._misses = 0
        self._stored = 0

    @property
    def stats(self) -> CacheStats:
        return CacheStats(hits=self._hits, misses=self._misses, stored=self._stored)

    def get(self, key: str) -> ModelCall | None:
        row = self._connection.execute(
            "SELECT key, model_id, prompt, params_json, response, prompt_tokens, "
            "completion_tokens, latency_ms, cost_usd, created_at "
            "FROM model_calls WHERE key = ?",
            (key,),
        ).fetchone()
        if row is None:
            self._misses += 1
            return None
        self._hits += 1
        return ModelCall(*row)

    def put(self, call: ModelCall) -> None:
        self._connection.execute(
            "INSERT OR REPLACE INTO model_calls "
            "(key, model_id, prompt, params_json, response, prompt_tokens, "
            "completion_tokens, latency_ms, cost_usd, created_at) "
            "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
            (
                call.key,
                call.model_id,
                call.prompt,
                call.params_json,
                call.response,
                call.prompt_tokens,
                call.completion_tokens,
                call.latency_ms,
                call.cost_usd,
                call.created_at,
            ),
        )
        self._connection.commit()
        self._stored += 1

    def totals(self) -> tuple[int, int, float]:
        """Total prompt tokens, completion tokens and cost across the whole cache."""
        row = self._connection.execute(
            "SELECT COALESCE(SUM(prompt_tokens), 0), COALESCE(SUM(completion_tokens), 0), "
            "COALESCE(SUM(cost_usd), 0.0) FROM model_calls"
        ).fetchone()
        return int(row[0]), int(row[1]), float(row[2])

    def __len__(self) -> int:
        row = self._connection.execute("SELECT COUNT(*) FROM model_calls").fetchone()
        return int(row[0])

    def close(self) -> None:
        self._connection.close()
