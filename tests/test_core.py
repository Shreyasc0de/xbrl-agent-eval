def test_ollama_constrains_output_to_json_by_default() -> None:
    """Measured, not assumed.

    On qwen3:4b every call ran to the full token cap producing chain of
    thought that never contained a JSON object, so every turn failed to parse
    and every task failed. Setting think to false did not suppress it. The
    grammar constraint makes the failure impossible rather than discouraged,
    and a model that cannot emit parseable output would otherwise score zero
    for reasons that say nothing about reading filings.
    """
    from core.llm import OllamaBackend

    captured: dict[str, object] = {}

    class FakeResponse:
        status_code = 200

        @staticmethod
        def json() -> dict[str, object]:
            return {"response": "{}", "prompt_eval_count": 1, "eval_count": 1}

    def fake_post(url: str, json: dict[str, object], timeout: float) -> FakeResponse:
        captured.update(json)
        return FakeResponse()

    import sys
    import types

    stub = types.ModuleType("requests")
    stub.post = fake_post  # type: ignore[attr-defined]
    original = sys.modules.get("requests")
    sys.modules["requests"] = stub
    try:
        OllamaBackend("qwen3:4b").complete("hi", {})
        assert captured["format"] == "json"
        assert captured["think"] is False

        captured.clear()
        OllamaBackend("qwen3:4b", json_mode=False).complete("hi", {})
        assert "format" not in captured
    finally:
        if original is not None:
            sys.modules["requests"] = original
        else:
            del sys.modules["requests"]


def test_a_run_that_called_nothing_refuses_to_write_results(tmp_path: Path) -> None:
    """The dangerous failure is not a crash, it is a run that completes having

    called nothing and writes a results file full of defaults.
    """
    run = manifest(model_calls=0)
    run.complete(1.0)
    with pytest.raises(ZeroModelCallsError):
        run.write(tmp_path / "manifest.json")
    assert not (tmp_path / "manifest.json").exists()


def test_a_run_served_entirely_from_cache_is_valid() -> None:
    run = manifest(model_calls=100, cache_hits=100, cache_misses=0)
    run.assert_work_happened()


def test_a_fresh_run_served_entirely_from_cache_is_rejected() -> None:
    """Either the cache is stale or the run type is wrong. Both are worth a stop."""
    run = manifest(model_calls=100, cache_hits=100, cache_misses=0)
    with pytest.raises(ZeroModelCallsError):
        run.assert_work_happened(allow_full_cache=False)


def test_a_manifest_written_before_completion_is_rejected(tmp_path: Path) -> None:
    run = manifest(model_calls=1)
    with pytest.raises(ValueError, match="wall clock"):
        run.write(tmp_path / "manifest.json")


def test_a_complete_manifest_carries_every_required_field(tmp_path: Path) -> None:
    run = manifest(model_calls=5, prompt_tokens=100, completion_tokens=50)
    run.complete(12.5)
    payload = run.write(tmp_path / "manifest.json")

    import json

    written = json.loads(payload.read_text(encoding="utf-8"))
    required = {
        "model_id",
        "temperature",
        "seed",
        "prompt_template_hash",
        "question_set_hash",
        "git_commit",
        "started_at",
        "finished_at",
        "wall_clock_seconds",
        "prompt_tokens",
        "completion_tokens",
        "total_cost_usd",
    }
    assert required <= set(written)
    assert written["total_tokens"] == 150


def test_git_commit_is_recorded_as_unknown_rather_than_omitted() -> None:
    """A reader must be able to tell a missing commit from an unrecorded one."""
    commit = git_commit()
    assert commit
    assert commit == "unknown" or len(commit.split("-")[0]) == 40
