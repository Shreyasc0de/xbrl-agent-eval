def test_the_same_call_hashes_the_same() -> None:
    assert call_key("m", "p", {"a": 1, "b": 2}) == call_key("m", "p", {"b": 2, "a": 1})


def test_a_different_model_is_a_different_key() -> None:
    assert call_key("m1", "p", {}) != call_key("m2", "p", {})


def test_a_different_temperature_is_a_different_key() -> None:
    assert call_key("m", "p", {"temperature": 0.0}) != call_key("m", "p", {"temperature": 0.7})


def test_a_changed_prompt_changes_the_template_hash() -> None:
    """An edited prompt must not inherit an old run's numbers."""
    assert prompt_template_hash("you are an analyst") != prompt_template_hash(
        "you are a careful analyst"
    )


