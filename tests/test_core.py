def test_a_repeated_call_is_served_from_cache(tmp_path: Path) -> None:
    scripted = ScriptedBackend(responses=["answer"])
    backend = CachingBackend(scripted, LLMCache(tmp_path / "calls.db"))

    first = backend.complete("prompt", {"temperature": 0.0})
    second = backend.complete("prompt", {"temperature": 0.0})

    assert first.text == second.text == "answer"
    assert len(scripted.calls) == 1
    assert backend.cache_hits == 1
    assert backend.cache_misses == 1
    assert backend.calls == 2


def test_a_changed_prompt_is_not_served_from_cache(tmp_path: Path) -> None:
    scripted = ScriptedBackend(responses=["first", "second"])
    backend = CachingBackend(scripted, LLMCache(tmp_path / "calls.db"))

    assert backend.complete("prompt one", {}).text == "first"
    assert backend.complete("prompt two", {}).text == "second"
    assert backend.cache_hits == 0


def test_a_backend_failure_propagates_rather_than_returning_empty(
    tmp_path: Path,
) -> None:
    """No silent fallbacks. A failed call fails the task."""
    backend = CachingBackend(ScriptedBackend(responses=[]), LLMCache(tmp_path / "calls.db"))
    with pytest.raises(ModelCallError):
        backend.complete("prompt", {})


def test_a_failed_call_is_not_cached(tmp_path: Path) -> None:
    cache = LLMCache(tmp_path / "calls.db")
    backend = CachingBackend(ScriptedBackend(responses=[]), cache)
    with pytest.raises(ModelCallError):
        backend.complete("prompt", {})
    assert len(cache) == 0


def test_usage_is_accumulated_across_calls(tmp_path: Path) -> None:
    scripted = ScriptedBackend(responses=["one two three", "four five"])
    backend = CachingBackend(scripted, LLMCache(tmp_path / "calls.db"))
    backend.complete("a b", {})
    backend.complete("c d e", {})
    assert backend.completion_tokens == 5
    assert backend.prompt_tokens == 5


