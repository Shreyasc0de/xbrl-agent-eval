def test_a_miss_returns_nothing_rather_than_a_placeholder(tmp_path: Path) -> None:
    cache = LLMCache(tmp_path / "calls.db")
    assert cache.get("absent") is None
    assert cache.stats.misses == 1


def test_a_stored_call_round_trips(tmp_path: Path) -> None:
    cache = LLMCache(tmp_path / "calls.db")
    cache.put(a_call())
    found = cache.get("k")
    assert found is not None
    assert found.response == "hello"
    assert found.total_tokens == 15


def test_the_cache_survives_being_reopened(tmp_path: Path) -> None:
    """This is what makes a rerun from a fresh process reproduce exactly."""
    path = tmp_path / "calls.db"
    first = LLMCache(path)
    first.put(a_call())
    first.close()

    second = LLMCache(path)
    found = second.get("k")
    assert found is not None
    assert found.response == "hello"


def test_totals_sum_tokens_and_cost(tmp_path: Path) -> None:
    cache = LLMCache(tmp_path / "calls.db")
    cache.put(a_call(key="one"))
    cache.put(a_call(key="two"))
    prompt_tokens, completion_tokens, cost = cache.totals()
    assert (prompt_tokens, completion_tokens, cost) == (20, 10, 0.0)


