"""Model call cache, run manifest, and the caching backend.

These are the modules that make a published number checkable, so most of what is
tested here is refusal: refusing to write results for a run that called nothing,
refusing to reuse a response generated by a different prompt, refusing to
fabricate a completion on a cache miss.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from core.cache import LLMCache, ModelCall, call_key
from core.llm import CachingBackend, ModelCallError, ScriptedBackend
from core.manifest import (
    RunManifest,
    ZeroModelCallsError,
    git_commit,
    prompt_template_hash,
)


def a_call(key: str = "k", response: str = "hello") -> ModelCall:
    return ModelCall(
        key=key,
        model_id="qwen3:4b",
        prompt="p",
        params_json="{}",
        response=response,
        prompt_tokens=10,
        completion_tokens=5,
        latency_ms=12.5,
        cost_usd=0.0,
        created_at="2026-01-01T00:00:00+00:00",
    )


def manifest(**overrides: object) -> RunManifest:
    base: dict[str, object] = {
        "run_id": "r1",
        "system": "A",
        "model_id": "qwen3:4b",
        "backend": "ollama",
        "temperature": 0.0,
        "seed": 7,
        "prompt_template_hash": "abc123",
        "question_set_hash": "def456",
        "question_count": 100,
    }
    base.update(overrides)
    return RunManifest(**base)  # type: ignore[arg-type]


